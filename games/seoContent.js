const SOLO_PLAYERS = { min: 1, max: 1 };

function playerRangeFor(id) {
    const mode = getAvailableGameModes().find(m => m.id === id);
    return mode ? { min: mode.minPlayers, max: mode.maxPlayers } : SOLO_PLAYERS;
}

function formatPlayers(range) {
    if (!range) return '';
    if (range.min === 1 && range.max === 1) return 'เล่นคนเดียว';
    return range.min === range.max ? `${range.min} คน` : `${range.min}–${range.max} คน`;
}

const BY_ID = new Map(GAMES.map(game => {
    const players = game.solo ? SOLO_PLAYERS : playerRangeFor(game.id);
    return [game.id, {
        ...game,
        solo: Boolean(game.solo),
        players,
        playersLabel: formatPlayers(players),
        path: `/games/${game.id}`,
        playUrl: game.solo ? `/solo/${game.id}` : `/rooms?mode=${game.id}`,
        rulesUrl: `/how-to-play#${game.id}`,
        ogImage: `/static/og/${game.id}.jpg`
    }];
}));

function getSeoGame(id) {
    return BY_ID.get(String(id || '')) || null;
}

function listSeoGames() {
    return Array.from(BY_ID.values());
}

